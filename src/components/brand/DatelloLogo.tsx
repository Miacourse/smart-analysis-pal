export function DatelloLogo({
  variant = "complet",
  dark = false,
  height = 32,
  className,
}: {
  variant?: Variant;
  dark?: boolean;
  height?: number;
  className?: string;
}) {
  const art = variant === "icone" ? ICON : ART[variant][dark ? "dark" : "light"];
  const [, , w = 1, h = 1] = art.viewBox.split(" ").map(Number);
  return (
    <svg
      viewBox={art.viewBox}
      height={height}
      width={Math.round((height * w) / h)}
      role="img"
      aria-label="Datello"
      className={className}
    >
      {art.body}
    </svg>
  );
}

